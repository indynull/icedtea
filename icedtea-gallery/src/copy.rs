use icedtea::i18n::Catalog;

/// Catalog keys filled for every gallery locale.
#[cfg(test)]
pub fn keys() -> impl Iterator<Item = &'static str> {
    ROWS.iter().map(|(k, ..)| *k)
}

/// Fill gallery keys for `lang` (en, vi, ja, zh, ar, ur, he).
pub fn fill(cat: &mut Catalog, lang: &str) {
    let primary = lang
        .split(['-', '_'])
        .next()
        .unwrap_or("en")
        .to_ascii_lowercase();
    if primary == "ar" {
        for (k, v) in AR {
            cat.insert(*k, *v);
        }
        return;
    }
    if primary == "ur" {
        for (k, v) in UR {
            cat.insert(*k, *v);
        }
        return;
    }
    if primary == "he" {
        for (k, v) in HE {
            cat.insert(*k, *v);
        }
        return;
    }
    for (k, en, vi, ja, zh) in ROWS {
        let v = match primary.as_str() {
            "vi" => vi,
            "ja" => ja,
            "zh" => zh,
            _ => en,
        };
        cat.insert(*k, *v);
    }
}

