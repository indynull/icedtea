pub fn markdown(lang: &str) -> &'static str {
    let primary = lang
        .split(['-', '_'])
        .next()
        .unwrap_or("en")
        .to_ascii_lowercase();
    match primary.as_str() {
        "vi" => MARKDOWN_VI,
        "ja" => MARKDOWN_JA,
        "zh" => MARKDOWN_ZH,
        "ar" => MARKDOWN_AR,
        "ur" => MARKDOWN_UR,
        "he" => MARKDOWN_HE,
        _ => crate::samples::MARKDOWN,
    }
}

